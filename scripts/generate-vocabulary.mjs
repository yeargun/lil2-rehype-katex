// Generates src/katex/vocabulary.lil: every attribute KaTeX 0.16.22 writes (its MathML, HTML and SVG builders,
// including the trusted \href, \includegraphics and \html* commands), read as hastscript reads it in the html
// schema (HTML and MathML elements) and the svg schema (SVG elements): the hast property and how the value
// parses; and every such property's JSX key and list joining per schema, as hast-util-to-jsx-runtime picks them.
import {readFileSync, writeFileSync} from 'node:fs'
import {createRequire} from 'node:module'
import {pathToFileURL} from 'node:url'
const require = createRequire(import.meta.url)
const pi = await import(pathToFileURL(require.resolve('property-information')).href)
const version = JSON.parse(readFileSync(new URL('../node_modules/property-information/package.json', import.meta.url), 'utf8')).version
const attributes = ['accent', 'accentunder', 'alt', 'aria-hidden', 'class', 'columnalign', 'columnlines', 'columnspacing', 'd', 'depth',
  'display', 'displaystyle', 'encoding', 'fence', 'height', 'href', 'id', 'largeop', 'linebreak', 'linethickness', 'lspace',
  'mathbackground', 'mathcolor', 'mathsize', 'mathvariant', 'maxsize', 'minsize', 'notation', 'preserveAspectRatio', 'rowlines',
  'rowspacing', 'rspace', 'scriptlevel', 'separator', 'src', 'stretchy', 'stroke-width', 'style', 'title', 'valign', 'viewBox',
  'voffset', 'width', 'x1', 'x2', 'xmlns', 'y1', 'y2']
// Value kinds (src/katex/parse.lil): 0 string, 1 space-separated list, 2 comma-separated list, 3 comma-or-space list,
// 4 number when numeric, 5 boolean when empty or equal to the name.
const kind = info => info.spaceSeparated ? 1 : info.commaSeparated ? 2 : info.commaOrSpaceSeparated ? 3 : info.number ? 4 : (info.boolean || info.overloadedBoolean) ? 5 : 0
const react = (schema, property) => { const info = pi.find(schema, property); return info.space ? (pi.hastToReact[info.property] || info.property) : info.attribute }
// The HTML parser lowercases attribute names, then adjusts these in SVG.
const svgAdjust = {viewbox: 'viewBox', preserveaspectratio: 'preserveAspectRatio'}
const rows = []
const properties = new Map()
for (const attribute of attributes) {
  const lower = attribute.toLowerCase()
  const html = pi.find(pi.html, lower), svg = pi.find(pi.svg, svgAdjust[lower] || lower)
  rows.push([lower, html.property, kind(html), svg.property, kind(svg)])
  for (const property of [html.property, svg.property]) {
    if (!properties.has(property)) properties.set(property, [react(pi.html, property), react(pi.svg, property), Boolean(pi.find(pi.html, property).commaSeparated), Boolean(pi.find(pi.svg, property).commaSeparated)])
  }
}
const list = a => '[' + a.map(v => JSON.stringify(v)).join(', ') + ']'
const col = i => list(rows.map(r => r[i]))
const props = [...properties]
writeFileSync(new URL('../src/katex/vocabulary.lil', import.meta.url), `// KaTeX's attributes in hast terms, from property-information ${version}. Generated by scripts/generate-vocabulary.mjs.

// By attribute (lowercased, as the HTML parser gives it): the property and value kind in the html schema and in
// the svg schema.
export string[] attributeNames = ${col(0)};
export string[] attributeProps = ${col(1)};
export int[] attributeKinds = ${col(2)};
export string[] attributePropsSvg = ${col(3)};
export int[] attributeKindsSvg = ${col(4)};

// By property: the JSX key and whether a list joins with commas, in the html and svg schemas.
export string[] propertyNames = ${list(props.map(p => p[0]))};
export string[] propertyReact = ${list(props.map(p => p[1][0]))};
export string[] propertyReactSvg = ${list(props.map(p => p[1][1]))};
export bool[] propertyComma = ${list(props.map(p => p[1][2]))};
export bool[] propertyCommaSvg = ${list(props.map(p => p[1][3]))};
`)
console.log(rows.length, 'attributes,', props.length, 'properties')
